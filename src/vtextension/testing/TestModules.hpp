#ifdef VTEXTENSION_TEST_MODULE_DIR
/// Reads a guest module built by the test target's wasm dependencies.
[[nodiscard]] inline std::vector<std::byte> readTestModule(std::string_view fileName)
{
    auto const path = std::string(VTEXTENSION_TEST_MODULE_DIR) + "/" + std::string(fileName);
    auto file = std::ifstream(path, std::ios::binary);
    REQUIRE(file.good());
    auto const chars =
        std::vector<char> { std::istreambuf_iterator<char>(file), std::istreambuf_iterator<char>() };
    auto bytes = std::vector<std::byte>(chars.size());
    std::ranges::transform(chars, bytes.begin(), [](char c) { return static_cast<std::byte>(c); });
    return bytes;
}
#endif

/// @return @p bytes as a module's bytes.
template <std::size_t N>
[[nodiscard]] std::vector<std::byte> toModule(std::array<uint8_t, N> const& bytes)
{
    auto module = std::vector<std::byte>(N);
    std::ranges::transform(bytes, module.begin(), [](uint8_t byte) { return static_cast<std::byte>(byte); });
    return module;
}

