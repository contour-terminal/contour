/// The character a keysym names.
///
/// A keysym is not a codepoint: Latin-1 keysyms are, but every other character set -- `XK_Cyrillic_a` is
/// 0x06C1 -- has keysyms laid out in X11's own numbering, and the keysyms of characters beyond them take the
/// `0x01000000 | codepoint` form.
/// @param keysym The X11 keysym.
/// @return The codepoint it names, or 0 for a keysym that names no character (Delete, an arrow, a modifier).
[[nodiscard]] constexpr char32_t keysymToCodepoint(uint32_t keysym) noexcept
{
    // Latin-1 keysyms are the codepoints themselves.
    if ((0x20 <= keysym && keysym <= 0x7E) || (0xA0 <= keysym && keysym <= 0xFF))
        return static_cast<char32_t>(keysym);

    if (keysym >= detail::X11UnicodeKeysymBase)
    {
        auto const codepoint = keysym - detail::X11UnicodeKeysymBase;
        return codepoint <= detail::MaxCodepoint ? static_cast<char32_t>(codepoint) : char32_t { 0 };
    }

    auto const i = std::ranges::lower_bound(detail::LegacyKeysymRows, keysym, {}, &KeysymRow::keysym);
    return i != detail::LegacyKeysymRows.end() && i->keysym == keysym ? i->codepoint : char32_t { 0 };
}

