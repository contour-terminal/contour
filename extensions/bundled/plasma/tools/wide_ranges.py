"""Writes plasma's table of double-width characters from the Unicode Character Database.

Every range whose East_Asian_Width is W (wide) or F (full-width), adjacent ranges merged, from the
EastAsianWidth.txt of the UCD libunicode builds from (its build tree holds it under _ucd/). Run it again,
with the newer file, when that UCD moves on:

    tools/wide_ranges.py <path to EastAsianWidth.txt> > src/wide_ranges.rs
"""

import re
import sys

LINE = re.compile(r"^([0-9A-F]{4,6})(?:\.\.([0-9A-F]{4,6}))?\s*;\s*(\w+)")


def wide_ranges(path):
    """@return The merged (first, last) ranges of the W and F code points in the file at @p path."""
    ranges = []
    with open(path, encoding="utf-8") as ucd:
        for line in ucd:
            match = LINE.match(line)
            if not match or match.group(3) not in ("W", "F"):
                continue
            first = int(match.group(1), 16)
            last = int(match.group(2) or match.group(1), 16)
            if ranges and ranges[-1][1] + 1 == first:
                ranges[-1] = (ranges[-1][0], last)
            else:
                ranges.append((first, last))
    return ranges


def main():
    path = sys.argv[1]
    version = re.search(r"EastAsianWidth-([0-9.]+)\.txt", open(path, encoding="utf-8").readline())
    ranges = wide_ranges(path)
    print("// SPDX-License-Identifier: Apache-2.0")
    print(f"// Generated by tools/wide_ranges.py from the UCD's EastAsianWidth"
          f"{'-' + version.group(1) if version else ''}.txt; do not edit.")
    print()
    print("/// The ranges of characters that take two cells: East_Asian_Width W and F, ascending, merged.")
    print(f"pub const DOUBLE_WIDTH: [(u32, u32); {len(ranges)}] = [")
    for first, last in ranges:
        print(f"    (0x{first:04X}, 0x{last:04X}),")
    print("];")


if __name__ == "__main__":
    main()
